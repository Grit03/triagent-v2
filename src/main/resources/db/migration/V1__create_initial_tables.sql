-- 1, 2단계에서 Hibernate가 자동으로 만들던 테이블을 마이그레이션으로 옮깁니다.
-- PostgreSQL과 테스트용 H2에서 모두 동작하는 표준 SQL만 사용합니다.

create table incident (
    id          bigint generated by default as identity primary key,
    fingerprint varchar(64)              not null,
    alert_name  varchar(255)             not null,
    service     varchar(255)             not null,
    severity    varchar(32)              not null,
    summary     varchar(1000),
    status      varchar(16)              not null,
    started_at  timestamp(6) with time zone not null,
    resolved_at timestamp(6) with time zone
);

create index idx_incident_fingerprint_status on incident (fingerprint, status);

create table remediation_action (
    id           bigint generated by default as identity primary key,
    incident_id  bigint                   not null,
    service      varchar(255)             not null,
    type         varchar(16)              not null,
    reason       varchar(1000),
    status       varchar(16)              not null,
    requested_by varchar(255)             not null,
    requested_at timestamp(6) with time zone not null,
    decided_by   varchar(255),
    decided_at   timestamp(6) with time zone,
    result       varchar(1000),
    finished_at  timestamp(6) with time zone
);

create table audit_log (
    id          bigint generated by default as identity primary key,
    occurred_at timestamp(6) with time zone not null,
    actor       varchar(255)             not null,
    type        varchar(32)              not null,
    incident_id bigint                   not null,
    action_id   bigint,
    detail      varchar(1000)
);

create index idx_audit_log_incident on audit_log (incident_id, occurred_at);
